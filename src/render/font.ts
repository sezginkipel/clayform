const BITS: Record<string, number[]> = {};
for (const [ch, rows] of Object.entries(G)) BITS[ch] = rows.split(' ').map((r) => parseInt(r, 2));

/** The 5×7 rows of a character ('1' = lit), or undefined if the font has none. */
export function glyph(ch: string): string[] | undefined {
	const g = G[ch.toUpperCase()];
	return g ? g.split(' ') : undefined;
}

export const GLYPH_W = 6;
export const GLYPH_H = 8;

export function textWidth(s: string, scale = 1): number {
	return s.length * GLYPH_W * scale;
}

/** Draw text into an RGBA buffer. */
export function drawText(
	buf: Uint8Array,
	width: number,
	height: number,
	x0: number,
	y0: number,
	text: string,
	color: [number, number, number],
	scale = 1
) {
	let x = x0;
	for (const raw of text.toUpperCase()) {
		const rows = BITS[raw] ?? BITS['#'];
		for (let r = 0; r < 7; r++)
			for (let c = 0; c < 5; c++) {
				if (!((rows[r] >> (4 - c)) & 1)) continue;
				for (let sy = 0; sy < scale; sy++)
					for (let sx = 0; sx < scale; sx++) {
						const px = x + c * scale + sx, py = y0 + r * scale + sy;
						if (px < 0 || py < 0 || px >= width || py >= height) continue;
						const o = (py * width + px) * 4;
						buf[o] = color[0];
						buf[o + 1] = color[1];
						buf[o + 2] = color[2];
						buf[o + 3] = 255;
					}
			}
		x += GLYPH_W * scale;
	}
}
